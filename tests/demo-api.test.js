import test from 'node:test';
import assert from 'node:assert/strict';
const entries = new Map();
Object.defineProperty(globalThis, 'localStorage', {value: {getItem: key => entries.get(key) ?? null, setItem: (key, value) => entries.set(key, value)}, configurable: true});
const {smartmed} = await import('../src/api/smartmed.js');

test('demo shared-lid cycle, edits, and immutable history', async () => {
  const instant = new Date('2027-01-15T02:34:00Z');
  await smartmed.simulate('open', instant);
  await assert.rejects(() => smartmed.simulate('open', instant), /Close the demo lid/);
  let w = await smartmed.load();
  assert.equal(w.events.length, 1);
  assert.equal(w.events[0].type, 'BOX_OPENED');
  assert.equal(w.device.lidState, 'OPEN');
  assert.equal(w.events[0].reminderContext.label, 'Morning');
  const newMedicine = {name: 'Example medicine', strength: '5 mg', quantity: '1 tablet', instructions: 'As prescribed', slotId: 'morning'};
  await smartmed.saveMedicine(newMedicine);
  w = await smartmed.load();
  assert.equal(w.medicines.filter(m => m.slotId === 'morning').length, 3);
  await smartmed.removeMedicine('m1');
  w = await smartmed.load();
  assert.equal(w.events[0].reminderContext.medicines[0].name, 'Metformin');
  await smartmed.simulate('close', instant);
  await smartmed.simulate('open', instant);
  w = await smartmed.load();
  assert.equal(w.events.filter(e => e.type === 'BOX_OPENED').length, 2);
  await smartmed.simulate('toggleConnection');
  await assert.rejects(() => smartmed.simulate('close', instant), /Reconnect/);
  assert.equal((await smartmed.load()).events.length, 3);
});
